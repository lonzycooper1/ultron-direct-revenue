export function videoBusinessMission({goal='',budgetUsd=0,timeHours=0}={}){
 const g=String(goal||'').toLowerCase();
 const relevant=/sell|product|guide|ebook|pdf|template|marketplace|gumroad|etsy|shopify|business|revenue|income|money|offer|customer|buyer|demand|problem|pain|passive|curat|knowledge|pre.?sell|preorder|funnel|audit|diagnostic|workflow|composio|tool|integration|tiktok|youtube|social|marketing|promot|digital/.test(g);
 if(!relevant)return {version:TIKTOK_BATCH_VERSION,goal:String(goal||'').slice(0,2000),matched:false,specialists:[],stages:[],approvalRequired:false,externalExecution:'none',strategy:null,toolDiscovery:TOOL_DISCOVERY_ARCHITECTURE,guardrails:VIDEO_BATCH_GUARDRAILS};
 const specialists=['RevenueClaimVerifierAgent'];
 const stages=['VALIDATE_DEMAND'];
 const add=(a,s)=>{if(!specialists.includes(a))specialists.push(a);if(s&&!stages.includes(s))stages.push(s)};
 if(/problem|pain|demand|what.*sell|people.*pay|opportunit/.test(g))add('PaidProblemMinerAgent','MINE_PAID_PROBLEMS');
 if(/guide|ebook|pdf|checklist|playbook/.test(g))add('RapidGuideFactoryAgent','BUILD_GUIDE');
 if(/name|brand|cover|graphic|package|listing/.test(g))add('ProductPackagingAgent','PACKAGE_PRODUCT');
 if(/marketplace|gumroad|etsy|shopify|upload|listing|sell/.test(g))add('MarketplaceLaunchAgent','STAGE_MARKETPLACE');
 if(/content|tiktok|youtube|social|market|promot|post/.test(g))add('MarketingCalendarAgent','BUILD_CONTENT_PLAN');
 if(/composio|tool|integration|app|connect|workflow|agent/.test(g))add('ToolDiscoveryBrokerAgent','DISCOVER_TOOLS');
 if(/passive|low.?maintenance|one hour|minimal/.test(g))add('LowMaintenanceOpportunityAgent','SCORE_MAINTENANCE');
 if(/curat|organize.*resource|existing.*information/.test(g))add('LicensedCurationAgent','VERIFY_RIGHTS');
 if(/create once|digital product|template|printable/.test(g))add('CreateOnceProductAgent','BUILD_REUSABLE_PRODUCT');
 if(/knowledge|7.?day|seven.?day|under.*\$|course/.test(g))add('KnowledgeProductSprintAgent','RUN_PRODUCT_SPRINT');
 if(/pre.?sell|preorder|early.?bird|waitlist|fomo/.test(g))add('PresellValidationAgent','VALIDATE_PRESELL');
 if(/funnel|free tool|checkout|automated delivery/.test(g))add('FreeToolFunnelAgent','BUILD_MINIMUM_FUNNEL');
 if(/audit|diagnostic|workflow gap|revenue leak/.test(g))add('EntryAuditAgent','BUILD_ENTRY_AUDIT');

 if(specialists.length===1){
  for(const [a,s] of [
   ['PaidProblemMinerAgent','MINE_PAID_PROBLEMS'],['CreateOnceProductAgent','BUILD_REUSABLE_PRODUCT'],
   ['MarketplaceLaunchAgent','STAGE_MARKETPLACE'],['MarketingCalendarAgent','BUILD_CONTENT_PLAN']
  ])add(a,s);
 }
 stages.push('QA_AND_RIGHTS','STAGE_NOT_PUBLISH','MEASURE_AND_LEARN');
 const consequential=/publish|post|send|launch ad|spend|charge|refund|connect account|pre.?sell|preorder/.test(g);
 return {
  version:TIKTOK_BATCH_VERSION,goal:String(goal||'').slice(0,2000),matched:true,
  specialists,stages,budgetUsd:Number(budgetUsd)||0,timeHours:Number(timeHours)||0,
  approvalRequired:consequential,
  externalExecution:consequential?'owner-approved-only':'research-build-and-stage',
  strategy:'validate paid problem -> build smallest legitimate offer -> leverage existing distribution -> verify payment -> fulfill -> measure -> iterate',
  toolDiscovery:TOOL_DISCOVERY_ARCHITECTURE,
  guardrails:VIDEO_BATCH_GUARDRAILS
 };
}

